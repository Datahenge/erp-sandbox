"""
guard.py — the Claude Code hook that makes "generated files are never
hand-edited" true rather than merely written down (decision #35).

`erp-sandbox render` writes a `PreToolUse` hook into the environment's
`.claude/settings.json`; Claude Code runs this before every Edit and Write and
obeys what it prints. An edit to a generated file is refused with a reason
naming the remedy, so the model is corrected rather than merely blocked.

**Everything here fails open.** A guard that refuses an edit because it could
not parse its own input, or because a password is missing from the shell, would
be worse than no guard at all: it would block real work for reasons the
developer cannot see. Every failure path returns "allow" silently. The cost of
failing open is one hand-edit that `erp-sandbox render --check` catches later,
which is the situation this exists to improve on, not to replace.

It binds Claude Code only. A human at a terminal, or VSCode, is unaffected.
"""

import json
import sys
from pathlib import Path

from erp_sandbox import project, render
from erp_sandbox.preflight import ConfigError, load_config

DENY_REASON = (
    "{relative} is generated by `erp-sandbox render` from config.toml, and the "
    "next render overwrites it -- so an edit here is lost, silently and "
    "without warning. Make the change in config.toml and run `erp-sandbox "
    "render`. If the value you need has no home in config.toml, say so rather "
    "than editing this file: that is a gap in the tool, not in the file. "
    "(Refused by erp-sandbox's edit guard.)"
)


def generated_paths(root):
    """
    The relative paths `erp-sandbox render` writes into `root`.

    Returns an empty list rather than raising when the configuration cannot be
    read: a broken config.toml must not make every file in the environment
    unwritable, least of all config.toml itself.
    """
    try:
        return render.output_paths(load_config(project.config_path(root)))
    except (ConfigError, OSError, ValueError):
        return []


def project_root_for(target):
    """
    The environment a file belongs to, found by walking up from the file.

    From the file rather than from the session's working directory: an edit to
    a generated file is by definition inside an environment, whatever directory
    the session happens to have started in -- which may be an app clone several
    levels down, or somewhere else entirely.
    """
    return project.find_project_root(target.parent, required=False)


def decide(payload, cwd=None):
    """
    The reason to refuse this tool call, or None to allow it.

    `payload` is what Claude Code writes on stdin. Only `tool_input.file_path`
    is load-bearing; the tool name is not consulted, because the matcher in
    settings.json has already done that job and a second, differently-spelled
    opinion about which tools write files is a way to disagree with it later.
    """
    file_path = (payload.get("tool_input") or {}).get("file_path")
    if not isinstance(file_path, str) or not file_path:
        return None

    target = Path(file_path)
    if not target.is_absolute():
        target = Path(cwd or payload.get("cwd") or ".") / target
    target = target.resolve()

    root = project_root_for(target)
    if root is None:
        return None

    try:
        relative = target.relative_to(root.resolve()).as_posix()
    except ValueError:
        return None

    if relative not in generated_paths(root):
        return None
    return DENY_REASON.format(relative=relative)


def main(argv=None, stdin=None, stdout=None):
    stdin = stdin if stdin is not None else sys.stdin
    stdout = stdout if stdout is not None else sys.stdout
    try:
        payload = json.load(stdin)
        if not isinstance(payload, dict):
            return 0
        reason = decide(payload)
    except Exception:       # deliberately broad: see the module docstring
        return 0

    if reason is None:
        return 0

    json.dump({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        },
    }, stdout)
    stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
